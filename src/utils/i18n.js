export function getLang() {
  try { return localStorage.getItem(LANGUAGE_KEY) || "pt"; } catch { return "pt"; }
}

export const LANGUAGE_CHANGE_EVENT = "hability-language-change";

export function setLang(lang) {
  try { localStorage.setItem(LANGUAGE_KEY, lang); } catch { /* Language preferences are optional when browser storage is unavailable. */ }
  try { window.dispatchEvent(new CustomEvent(LANGUAGE_CHANGE_EVENT, { detail: lang })); } catch { /* Language preferences are optional when browser storage is unavailable. */ }
}

export function t(key, params) {
  const lang = getLang();
  const table = dict[lang] || dict.pt;
  const parts = key.split(".");
  let value = parts.reduce((acc, k) => (acc && acc[k] != null ? acc[k] : undefined), table);
  if (value == null) return key;
  if (typeof value === "string" && params && typeof params === "object") {
    return value.replace(/\{\{(\w+)\}\}/g, (_, k) => (params[k] ?? ""));
  }
  return value;
}
